let lang = 'ja';
export function detectLang() {
  const nav = (navigator.languages && navigator.languages[0]) || navigator.language || 'en';
  const l = nav.toLowerCase();
  if (l.startsWith('ja')) return 'ja';
  if (l.startsWith('zh')) return /tw|hk|mo|hant/.test(l) ? 'zh-Hant' : 'zh-Hans';
  if (l.startsWith('ko')) return 'ko';
  if (l.startsWith('es')) return 'es';
  return 'en';
}
export function setLang(code) {
  lang = S[code] ? code : 'en';
  document.documentElement.lang = lang;
  applyStatic();
}
export const getLang = () => lang;
export const langName = (code) => (LANGS.find((l) => l.code === code) || LANGS[1]).name;

// t('key', {param}) -> localised string (falls back to English, then Japanese)
export function t(key, params) {
  let s = (S[lang] && S[lang][key]) || S.en[key] || S.ja[key] || key;
  if (params) s = s.replace(/\{(\w+)\}/g, (m, k) => (params[k] !== undefined ? params[k] : m));
  return s;
}

// elements marked with data-i18n / data-i18n-aria in index.html
export function applyStatic() {
  document.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = t(el.dataset.i18n); });
  document.querySelectorAll('[data-i18n-aria]').forEach((el) => el.setAttribute('aria-label', t(el.dataset.i18nAria)));
}
